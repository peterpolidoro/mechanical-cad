import pytest

from mechanical_cad import stepfile as S

DATA = (b"DATA;\r\n#1=( LENGTH_UNIT() NAMED_UNIT(*) SI_UNIT(.MILLI.,.METRE.) );\r\n"
        b"#2=( GEOMETRIC_REPRESENTATION_CONTEXT(3) GLOBAL_UNIT_ASSIGNED_CONTEXT((#1,#3,#4)) REPRESENTATION_CONTEXT('','3D') );\r\n"
        b"#9=PRODUCT('semi;colon and ''quote''','',$,(#8));\r\nENDSEC;\r\nEND-ISO-10303-21;\r\n")

# as Inventor's translator writes it: comments between fields and a long name wrapped inside the string
INVENTOR = (b"ISO-10303-21;\r\nHEADER;\r\n/* Generated by software containing ST-Developer\r\n * from STEP Tools, Inc. */\r\n\r\n"
            b"FILE_DESCRIPTION(\r\n/* description */ (''),\r\n/* implementation_level */ '2;1');\r\n\r\n"
            b"FILE_NAME(\r\n/* name */ \r\n'A LONG PART NAME__[Primary]__56fa5cf0.s\r\ntep',\r\n"
            b"/* time_stamp */ '2026-10-21T15:08:55-04:00',\r\n/* author */ ('someone'),\r\n/* organization */ (''),\r\n"
            b"/* preprocessor_version */ 'ST-DEVELOPER v20',\r\n/* originating_system */ 'Autodesk Inventor 2025',\r\n"
            b"/* authorisation */ '');\r\n\r\nFILE_SCHEMA (('AUTOMOTIVE_DESIGN { 1 0 10303 214 3 1 1 }'));\r\nENDSEC;\r\n\r\n") + DATA


def test_header_fields_with_comments_and_a_wrapped_string():
    h = S.header(INVENTOR)
    assert h["name"] == "A LONG PART NAME__[Primary]__56fa5cf0.step"
    assert h["time_stamp"] == "2026-10-21T15:08:55-04:00"
    assert h["author"] == ["someone"] and h["organization"] == [""]
    assert h["originating_system"] == "Autodesk Inventor 2025"
    assert h["protocol"] == "AP214"


def test_data_hash_ignores_the_header():
    other = INVENTOR.replace(b"2026-10-21T15:08:55-04:00", b"2026-10-21T11:49:29-04:00").replace(b"someone", b"else")
    assert S.sha256_bytes(other) != S.sha256_bytes(INVENTOR)
    assert S.data_sha256(other) == S.data_sha256(INVENTOR) == S.sha256_bytes(DATA)


def test_data_keyword_inside_a_header_string_is_not_the_data_section():
    tricky = INVENTOR.replace(b"('someone')", b"('ENDSEC; DATA; x')")
    assert S.data_sha256(tricky) == S.sha256_bytes(DATA)


def test_normalise_changes_only_file_name():
    n = S.normalise_header(INVENTOR)
    h = S.header(n)
    assert (h["name"], h["time_stamp"], h["author"], h["organization"], h["authorisation"]) == \
        ("part.step", S.NORMALISED_TIMESTAMP, [""], [""], "")
    assert h["preprocessor_version"] == "ST-DEVELOPER v20" and h["originating_system"] == "Autodesk Inventor 2025"
    assert S.data_sha256(n) == S.data_sha256(INVENTOR)
    assert b"FILE_DESCRIPTION(\r\n/* description */ ('')" in n          # the rest of the header is untouched
    assert b"someone" not in n
    assert S.is_normalised(n) and not S.is_normalised(INVENTOR)
    assert S.normalise_header(n) == n                                    # idempotent


def test_two_exports_of_one_version_normalise_to_the_same_bytes():
    second = INVENTOR.replace(b"2026-10-21T15:08:55-04:00", b"2026-10-21T18:10:00-04:00").replace(
        b"A LONG PART NAME__[Primary]__56fa5cf0.s\r\ntep", b"A LONG PART NAME.step")
    assert S.normalise_header(second) == S.normalise_header(INVENTOR)


@pytest.mark.parametrize("unit_entity, expected", [
    (b"( LENGTH_UNIT() NAMED_UNIT(*) SI_UNIT(.MILLI.,.METRE.) )", "mm"),
    (b"( LENGTH_UNIT() NAMED_UNIT(*) SI_UNIT(.CENTI.,.METRE.) )", "cm"),
    (b"( LENGTH_UNIT() NAMED_UNIT(*) SI_UNIT($,.METRE.) )", "m"),
    (b"( CONVERSION_BASED_UNIT('INCH',#5) LENGTH_UNIT() NAMED_UNIT(#6) )", "in"),
])
def test_length_unit(unit_entity, expected):
    data = INVENTOR.replace(b"( LENGTH_UNIT() NAMED_UNIT(*) SI_UNIT(.MILLI.,.METRE.) )", unit_entity)
    assert S.length_unit(data) == expected


def test_length_unit_problems_are_errors():
    with pytest.raises(S.StepFileError, match="GLOBAL_UNIT_ASSIGNED_CONTEXT"):
        S.length_unit(INVENTOR.replace(b"GLOBAL_UNIT_ASSIGNED_CONTEXT", b"SOMETHING_ELSE"))
    with pytest.raises(S.StepFileError, match="unknown conversion"):
        S.length_unit(INVENTOR.replace(b"( LENGTH_UNIT() NAMED_UNIT(*) SI_UNIT(.MILLI.,.METRE.) )",
                                       b"( CONVERSION_BASED_UNIT('CUBIT',#5) LENGTH_UNIT() NAMED_UNIT(#6) )"))


def test_files_that_are_not_step():
    with pytest.raises(S.StepFileError):
        S.sections(b"hello")
    with pytest.raises(S.StepFileError):
        S.sections(b"ISO-10303-21;\nHEADER;\nFILE_NAME('x');\n")
    with pytest.raises(S.StepFileError, match="unterminated"):
        S.sections(b"ISO-10303-21;\nHEADER;\nFILE_NAME('x);\nENDSEC;\nDATA;\n")


@pytest.mark.parametrize("schema, protocol", [
    ("AP242_MANAGED_MODEL_BASED_3D_ENGINEERING_MIM_LF { 1 0 10303 442 1 1 4 }", "AP242"),
    ("CONFIG_CONTROL_DESIGN", "AP203"),
    ("AP203_CONFIGURATION_CONTROLLED_3D_DESIGN_OF_MECHANICAL_PARTS_AND_ASSEMBLIES_MIM_LF", "AP203E2"),
    ("SOMETHING_ELSE", None),
])
def test_protocol_names(schema, protocol):
    data = INVENTOR.replace(b"AUTOMOTIVE_DESIGN { 1 0 10303 214 3 1 1 }", schema.encode())
    assert S.header(data)["protocol"] == protocol


def test_fixture_files(fixture_dir):
    plate = (fixture_dir / "references/parts/base-plate/part.step").read_bytes()
    pin = (fixture_dir / "references/parts/pin/part.step").read_bytes()
    assert S.is_normalised(plate) and not S.is_normalised(pin)
    assert S.header(pin)["author"] == ["fixture-author"]
    assert S.length_unit(plate) == "mm"


def test_product_name_is_set_without_touching_anything_else():
    occt = b"#9 = PRODUCT('Open CASCADE STEP translator 7.9 3',\r\n  'Open CASCADE STEP translator 7.9 3','',(#8));"
    data = INVENTOR.replace(b"#9=PRODUCT('semi;colon and ''quote''','',$,(#8));", occt)
    assert occt in data
    named = S.set_product_name(data, "spacer")
    assert b"#9 = PRODUCT('spacer',\r\n  'spacer','',(#8));" in named
    assert named.replace(b"'spacer'", b"'Open CASCADE STEP translator 7.9 3'") == data
    assert S.set_product_name(named, "spacer") == named
    assert S.set_product_name(data.replace(b"7.9 3", b"7.9 1"), "spacer") == named      # the export counter no longer matters
    assert b"PRODUCT('it''s'," in S.set_product_name(data, "it's")
    two = data.replace(b"ENDSEC;\r\nEND-ISO", b"#10=PRODUCT('b','b','',(#8));\r\nENDSEC;\r\nEND-ISO")
    with pytest.raises(S.StepFileError, match="expected one PRODUCT entity, found 2"):
        S.set_product_name(two, "x")
    with pytest.raises(S.StepFileError, match="found 0"):
        S.set_product_name(data.replace(b"PRODUCT(", b"PRODUKT("), "x")


# the entities Inventor's AP242 translator writes for a part with three bodies of which two are hidden
HIDDEN = (b"ISO-10303-21;\r\nHEADER;\r\nFILE_DESCRIPTION((''),'2;1');\r\n"
          b"FILE_NAME('p.step','2026-01-01T00:00:00',(''),(''),'','','');\r\n"
          b"FILE_SCHEMA(('AP242_MANAGED_MODEL_BASED_3D_ENGINEERING_MIM_LF { 1 0 10303 442 1 1 4 }'));\r\nENDSEC;\r\nDATA;\r\n"
          b"#10=MECHANICAL_DESIGN_GEOMETRIC_PRESENTATION_REPRESENTATION('',(#20,#21,#22),#90);\r\n"
          b"#15=ADVANCED_BREP_SHAPE_REPRESENTATION('[Primary]',(#32),#90);\r\n"
          b"#19=INVISIBILITY((#20,#20,#21,#21));\r\n"
          b"#20=STYLED_ITEM('',(#80),#30);\r\n#21=STYLED_ITEM('',(#80),#31);\r\n#22=STYLED_ITEM('',(#80),#32);\r\n"
          b"#30=MANIFOLD_SOLID_BREP('Solid;1',#40);\r\n#31=MANIFOLD_SOLID_BREP('Solid2',#41);\r\n"
          b"#32=MANIFOLD_SOLID_BREP('Solid3',#42);\r\n"
          b"#60=SHAPE_REPRESENTATION('',(#70,#30,\r\n #31,#32),#90);\r\n"
          b"ENDSEC;\r\nEND-ISO-10303-21;\r\n")
MARK = b"#19=INVISIBILITY((#20,#20,#21,#21));\r\n"
ITEMS = b"#60=SHAPE_REPRESENTATION('',(#70,#30,\r\n #31,#32),#90);\r\n"


def test_invisible_items_are_found_and_left_out():
    assert S.invisible_items(HIDDEN) == [30, 31]
    assert S.header(HIDDEN)["protocol"] == "AP242"
    visible = S.visible_only(HIDDEN)
    # two statements change and nothing else: the mark goes, and the representation lists the visible item only
    assert visible == HIDDEN.replace(MARK, b"").replace(b"(#70,#30,\r\n #31,#32)", b"(#70,#32)")
    assert S.invisible_items(visible) == [] and S.visible_only(visible) == visible
    # the kind of item does not matter: a hidden solid with an internal void is a BREP_WITH_VOIDS
    voids = HIDDEN.replace(b"#31=MANIFOLD_SOLID_BREP('Solid2',#41);", b"#31=BREP_WITH_VOIDS('Solid2',#41,(#43));")
    assert voids != HIDDEN and S.invisible_items(voids) == [30, 31]
    assert S.visible_only(voids) == voids.replace(MARK, b"").replace(b"(#70,#30,\r\n #31,#32)", b"(#70,#32)")


def test_a_file_that_marks_nothing_invisible_is_returned_as_it_is():
    assert S.invisible_items(INVENTOR) == []
    assert S.visible_only(INVENTOR) is INVENTOR
    in_a_string = HIDDEN.replace(MARK, b"").replace(b"'Solid2'", b"'INVISIBILITY'")
    assert S.visible_only(in_a_string) == in_a_string


@pytest.mark.parametrize("old, new, message", [
    (MARK, b"#19=INVISIBILITY((#30));\r\n", "hides #30, which is not a STYLED_ITEM"),
    (MARK, b"#19=INVISIBILITY((#99));\r\n", "hides #99, which is not a STYLED_ITEM"),
    (ITEMS, ITEMS + b"#95=MAPPED_ITEM('',#96,#30);\r\n", r"#30 is marked invisible and is used by #95 \(MAPPED_ITEM\)"),
    (ITEMS, ITEMS + b"#95=(REPRESENTATION('',(#30),#90) SHAPE_REPRESENTATION());\r\n", "used by #95 \\(a complex instance\\)"),
    (ITEMS, b"", "#30 is marked invisible but is not an item of any representation"),
    (ITEMS, b"#60=SHAPE_REPRESENTATION('',(#30,#31),#90);\r\n", "every item of #60 SHAPE_REPRESENTATION is marked invisible"),
    (ITEMS, b"#60=SHAPE_REPRESENTATION('',(#70,#31,#32),#30);\r\n", "#60 SHAPE_REPRESENTATION uses an invisible item outside"),
    (b"#20=STYLED_ITEM('',(#80),#30);", b"#20=STYLED_ITEM('',(#80));", "#20 STYLED_ITEM does not name the item it styles"),
])
def test_invisibility_that_is_not_understood_is_refused(old, new, message):
    assert old in HIDDEN
    with pytest.raises(S.StepFileError, match=message):
        S.visible_only(HIDDEN.replace(old, new))


def test_describe_counts_the_invisible_items(tmp_path):
    path = tmp_path / "p.step"
    path.write_bytes(HIDDEN.replace(b"DATA;\r\n", b"DATA;\r\n#1=( LENGTH_UNIT() NAMED_UNIT(*) SI_UNIT(.MILLI.,.METRE.) );\r\n"))
    assert S.describe(path)["invisible_items"] == 2
    path.write_bytes(HIDDEN.replace(MARK, b"#19=INVISIBILITY((#30));\r\n"))
    info = S.describe(path)
    assert info["invisible_items"] is None and "not a STYLED_ITEM" in info["invisible_items_error"]
